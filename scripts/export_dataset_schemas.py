"""Publish self-contained dataset collection schemas from their object schemas.

The source objects in schemas/ remain the normative contracts. Collections
embed their definitions so clients need no network reference resolution.
Run this after changing a source schema; --check rejects stale generated files.
"""

from __future__ import annotations

import argparse
import copy
import json
import sys
from pathlib import Path
from typing import Any

SCHEMAS_DIR = Path(__file__).resolve().parents[1] / "schemas"
COLLECTIONS = {
    "dataset-list": ("DatasetList", ("dataset-info",)),
    "dataset-splits": ("DatasetSplits", ("dataset-split",)),
    "dataset-item-summary-list": ("DatasetItemSummaryList", ("dataset-item-summary",)),
    "dataset-sample": ("DatasetSample", ("dataset-item",)),
    # The existing capability reference is shared by summary listings and
    # full-item samples. Dedicated REST bindings select the precise variant.
    "dataset-item-list": ("DatasetItemList", ("dataset-item-summary", "dataset-item")),
    "dataset-sync-report": ("DatasetSyncReport", ("dataset-sync-entry",)),
}


def build(schemas_dir: Path = SCHEMAS_DIR) -> dict[Path, str]:
    result: dict[Path, str] = {}
    for name, (title, sources) in COLLECTIONS.items():
        definitions: dict[str, Any] = {}
        choices = []
        for source in sources:
            schema = copy.deepcopy(json.loads(
                (schemas_dir / f"{source}@1.json").read_text(encoding="utf-8")
            ))
            definition = schema["title"]
            schema.pop("$schema")
            schema.pop("$id")
            for key, value in schema.pop("definitions", {}).items():
                if key in definitions and definitions[key] != value:
                    raise ValueError(f"conflicting dataset definition {key}")
                definitions[key] = value
            definitions[definition] = schema
            choices.append({"$ref": f"#/definitions/{definition}"})
        output = {
            "$schema": "http://json-schema.org/draft-07/schema#",
            "$id": f"urn:a11y-devs:schema:{name}:1",
            "title": title,
            "$comment": "Generated by scripts/export_dataset_schemas.py; do not edit by hand.",
            "type": "array",
            "items": choices[0] if len(choices) == 1 else {"anyOf": choices},
            "definitions": definitions,
        }
        result[schemas_dir / f"{name}@1.json"] = json.dumps(output, indent=2) + "\n"
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = []
    for path, text in build().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path}")
    if stale:
        print(f"stale dataset schemas: {stale}; run {Path(__file__).name}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
