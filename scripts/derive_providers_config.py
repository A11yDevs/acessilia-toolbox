"""Derive the default provider set from providers-config.yaml.

``providers-config.yaml`` registers every provider the Toolbox has, including
the optional sidecars that no client of the Acessilia core calls today (#108):

=============  ===============  ==========================
provider       sidecar service  Compose profile to opt in
=============  ===============  ==========================
``audiveris``  audiveris-serve  ``music``
``nougat``     nougat-serve     ``nougat``
=============  ===============  ==========================

A deployment that does not start those sidecars must not announce them either,
or its catalogue would list providers it cannot reach. This script writes
``deploy/providers-config.default.yaml``: the same providers, in the same order
and with the same values, without the optional ones. Production mounts it,
and the local and staging Compose files use it unless
``TOOLBOX_PROVIDERS_CONFIG`` points at the full file. It is generated, never
edited by hand; ``tests/unit/test_optional_sidecars.py`` fails when it is
stale.

Usage:
    python scripts/derive_providers_config.py           # rewrite the file
    python scripts/derive_providers_config.py --check   # exit 1 if it is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE = REPO_ROOT / "providers-config.yaml"
TARGET = REPO_ROOT / "deploy" / "providers-config.default.yaml"

#: Optional provider id -> the Compose profile that starts its sidecar.
OPTIONAL_PROVIDERS: dict[str, str] = {"audiveris": "music", "nougat": "nougat"}

HEADER = (
    "# Generated by scripts/derive_providers_config.py from providers-config.yaml;\n"
    "# do not edit by hand. Every provider except the optional sidecars, which\n"
    "# start only under their Compose profiles: {optional}.\n"
)


def derive(source_text: str) -> str:
    data = yaml.safe_load(source_text)
    providers = data["providers"]
    ids = {provider["id"] for provider in providers}
    missing = sorted(set(OPTIONAL_PROVIDERS) - ids)
    if missing:
        raise ValueError(f"optional providers not in providers-config.yaml: {missing}")
    kept = [p for p in providers if p["id"] not in OPTIONAL_PROVIDERS]
    optional = ", ".join(
        f"{provider} ({profile})" for provider, profile in OPTIONAL_PROVIDERS.items()
    )
    body = yaml.safe_dump(
        {**data, "providers": kept}, sort_keys=False, allow_unicode=True
    )
    return HEADER.format(optional=optional) + body


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is stale")
    args = parser.parse_args(argv)

    text = derive(SOURCE.read_text(encoding="utf-8"))
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(
                f"{TARGET.relative_to(REPO_ROOT)} is stale: "
                "run python scripts/derive_providers_config.py",
                file=sys.stderr,
            )
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
