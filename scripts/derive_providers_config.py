"""Derive one provider file per set of enabled optional sidecars.

``providers-config.yaml`` registers every provider the Toolbox has, including
the optional sidecars that no client of the Acessilia core calls today (#108):

=============  ===============  ==========================
provider       sidecar service  Compose profile to opt in
=============  ===============  ==========================
``audiveris``  audiveris-serve  ``music``
``nougat``     nougat-serve     ``nougat``
=============  ===============  ==========================

A deployment must announce exactly the optional providers whose sidecars it
starts: a catalogue listing a provider it cannot reach, or one sidecar's
provider when only the other runs, breaks the agreement between catalogue and
deployment. So this script writes one file per set of enabled profiles, with
the same providers, in the same order and with the same values as
``providers-config.yaml``, minus the optional ones that are off:

==================  ===========================================
profiles enabled    provider file (``TOOLBOX_COMPOSE_PROVIDERS_CONFIG``)
==================  ===========================================
none                ``deploy/providers-config.default.yaml`` (the default)
``music``           ``deploy/providers-config.music.yaml``
``nougat``          ``deploy/providers-config.nougat.yaml``
``music,nougat``    ``providers-config.yaml`` itself
==================  ===========================================

Production mounts the default file. The files are generated, never edited by
hand; ``tests/unit/test_optional_sidecars.py`` fails when one is stale.

Usage:
    python scripts/derive_providers_config.py           # rewrite the files
    python scripts/derive_providers_config.py --check   # exit 1 if one is stale
"""

from __future__ import annotations

import argparse
import itertools
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
SOURCE = REPO_ROOT / "providers-config.yaml"
DEPLOY_DIR = REPO_ROOT / "deploy"

#: Optional provider id -> the Compose profile that starts its sidecar.
OPTIONAL_PROVIDERS: dict[str, str] = {"audiveris": "music", "nougat": "nougat"}

HEADER = (
    "# Generated by scripts/derive_providers_config.py from providers-config.yaml;\n"
    "# do not edit by hand. Every provider except the optional sidecars whose\n"
    "# Compose profile is off. Optional sidecars: {optional}.\n"
    "# Profiles enabled for this file: {enabled}.\n"
)


def path_for(profiles: frozenset[str]) -> Path:
    """The provider file for a set of enabled profiles (the full file for all)."""
    if profiles == frozenset(OPTIONAL_PROVIDERS.values()):
        return SOURCE
    name = "+".join(sorted(profiles)) if profiles else "default"
    return DEPLOY_DIR / f"providers-config.{name}.yaml"


def derive(source_text: str, profiles: frozenset[str] = frozenset()) -> str:
    """The provider file for ``profiles``: the full file without disabled optionals."""
    data = yaml.safe_load(source_text)
    providers = data["providers"]
    ids = {provider["id"] for provider in providers}
    missing = sorted(set(OPTIONAL_PROVIDERS) - ids)
    if missing:
        raise ValueError(f"optional providers not in providers-config.yaml: {missing}")
    unknown = sorted(profiles - set(OPTIONAL_PROVIDERS.values()))
    if unknown:
        raise ValueError(f"unknown optional profiles: {unknown}")
    disabled = {pid for pid, profile in OPTIONAL_PROVIDERS.items() if profile not in profiles}
    kept = [p for p in providers if p["id"] not in disabled]
    optional = ", ".join(
        f"{provider} ({profile})" for provider, profile in OPTIONAL_PROVIDERS.items()
    )
    body = yaml.safe_dump({**data, "providers": kept}, sort_keys=False, allow_unicode=True)
    enabled = ", ".join(sorted(profiles)) or "none"
    return HEADER.format(optional=optional, enabled=enabled) + body


def outputs() -> dict[Path, str]:
    """Every derived file and its content: each proper subset of the profiles."""
    source = SOURCE.read_text(encoding="utf-8")
    profiles = sorted(OPTIONAL_PROVIDERS.values())
    files: dict[Path, str] = {}
    for size in range(len(profiles)):
        for subset in itertools.combinations(profiles, size):
            enabled = frozenset(subset)
            files[path_for(enabled)] = derive(source, enabled)
    return files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a file is stale")
    args = parser.parse_args(argv)

    files = outputs()
    if args.check:
        stale = [
            path
            for path, text in files.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != text
        ]
        for path in stale:
            print(
                f"{path.relative_to(REPO_ROOT)} is stale: "
                "run python scripts/derive_providers_config.py",
                file=sys.stderr,
            )
        return 1 if stale else 0
    for path, text in files.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
